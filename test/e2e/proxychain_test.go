//go:build e2e

package e2e

import (
	"context"
	"fmt"
	"os/exec"
	"testing"
	"time"
)

func TestProxyChain(t *testing.T) {
	t.Run("trusted", func(t *testing.T) {
		checkProxyChain(t, "remora", "trusted")
	})
	t.Run("untrusted", func(t *testing.T) {
		name := fmt.Sprintf("remora-e2e-untrusted-%d", time.Now().UnixNano())
		if out, err := compose(t, "run", "-d", "--rm", "--no-deps", "--name", name,
			"-e", "REMORA_TRUSTED_PROXIES=", "remora"); err != nil {
			t.Fatalf("start untrusted fixture: %v\n%s", err, out)
		}
		t.Cleanup(func() {
			ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
			defer cancel()
			//nolint:gosec // G204: the container name is generated by the test above.
			if err := exec.CommandContext(ctx, "docker", "stop", name).Run(); err != nil {
				t.Errorf("stop untrusted fixture: %v", err)
			}
		})
		checkProxyChain(t, name, "untrusted")
	})
}

func checkProxyChain(t *testing.T, host, trust string) {
	t.Helper()
	// The remora image has Bash but no curl; a one-off client container uses the compose network without publishing ports.
	if out, err := compose(t, "run", "--rm", "--no-deps", "-T", "--entrypoint", "bash", "remora",
		"-euc", proxyChainClient, "--", host, trust); err != nil {
		t.Fatalf("proxy chain: %v\n%s", err, out)
	}
}

const proxyChainClient = `
host=$1
trust=$2
for (( i=0; i<60; i++ )); do
    if remora healthcheck "http://$host:8080/healthz" >/dev/null 2>&1; then break; fi
    sleep 1
done

login() {
    local body line start
    printf -v body '{"password":"%s"}' "$2"
    start=${EPOCHREALTIME/./}
    exec 3<>"/dev/tcp/$host/8080"
    printf 'POST /api/auth/login HTTP/1.1\r\nHost: %s\r\nConnection: close\r\nContent-Type: application/json\r\nContent-Length: %s\r\nX-Forwarded-For: 192.0.2.99, %s, 10.0.0.2\r\nX-Forwarded-Proto: https\r\n\r\n%s' \
        "$host" "${#body}" "$1" "$body" >&3
    read -rt 35 _ status _ <&3
    elapsed=$(( ${EPOCHREALTIME/./} - start ))
    secure=0
    while IFS= read -rt 35 line <&3 && [[ $line != $'\r' ]]; do
        if [[ ${line,,} == set-cookie:*'; secure'* ]]; then secure=1; fi
    done
    exec 3>&-
}

for (( i=0; i<5; i++ )); do
    login 198.51.100.1 wrong-password
    [[ $status == 401 ]] || { echo "failed login: expected 401, got $status"; exit 1; }
done
login 198.51.100.2 "$REMORA_ADMIN_PASSWORD"
[[ $status == 204 ]] || { echo "second client: expected 204, got $status"; exit 1; }
if [[ $trust == trusted ]]; then
    [[ $secure == 1 && $elapsed -lt 1000000 ]] || { echo "trusted second client: secure=$secure elapsed=$elapsed us"; exit 1; }
    login 198.51.100.1 "$REMORA_ADMIN_PASSWORD"
    [[ $status == 204 && $elapsed -ge 1000000 ]] || { echo "first client did not keep its delay: status=$status elapsed=$elapsed us"; exit 1; }
else
    [[ $secure == 0 && $elapsed -ge 1000000 ]] || { echo "untrusted headers were used: secure=$secure elapsed=$elapsed us"; exit 1; }
fi
`
